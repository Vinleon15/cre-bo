"""Защита качества: что нельзя сжимать, когда расширять контекст, что проверять.

Асимметрия намеренная: расширить контекст стоит денег, потерять условие в
договоре стоит дороже. Поэтому при любом сомнении система берёт больше
контекста, а не меньше.
"""

from __future__ import annotations

import re

# Маркер, которым модель сообщает, что данных не хватает. Инструкция про него
# лежит в system-промпте; ответ с маркером пользователю не показывается —
# вместо этого запрос повторяется с полным контекстом.
INSUFFICIENT = "<<INSUFFICIENT>>"

# Вопросы, на которых экономить нельзя вообще. Проверяются ДО выбора режима
# и перекрывают любую настройку экономии.
FORCE_FULL_RE = re.compile(
    r"\bрассчитай\b|\bрасчёт\b|\bрасчет\b|\bпосчитай\b|\bсверь\b|\bсверка\b"
    r"|\bдоговор\b|\bконтракт\b|\bсоглашени|\bюридич|\bприлож.{0,3}\s*№"
    r"|\bсравни\b|\bверси[яию]\b|\bредакци"
    r"|\bпроверь\b|\bточно ли\b|\bфактчек|\bперепровер"
    r"|\bполность[юи]\b|\bвесь документ\b|\bвсе условия\b"
    r"|\bштраф|\bпен[яию]\b|\bнеустойк|\bналог|\bНДС\b",
    re.I,
)

# Дословно сохраняемые фрагменты: при вытеснении хода из истории они уходят
# в пины, а не в пересказ. Пересказ теряет отрицания и модальность.
PIN_PATTERNS = [
    ("сумма", re.compile(r"[^.\n]{0,60}\d[\d\s.,]*\s*(?:руб|₽|\$|€|тыс|млн|млрд)[^.\n]{0,60}", re.I)),
    ("процент", re.compile(r"[^.\n]{0,60}\d+[.,]?\d*\s*%[^.\n]{0,60}")),
    ("дата", re.compile(r"[^.\n]{0,60}\b\d{1,2}[.\-/]\d{1,2}[.\-/]\d{2,4}\b[^.\n]{0,60}")),
    ("срок", re.compile(r"[^.\n]{0,80}(?:не позднее|в течение|до\s+\d)[^.\n]{0,80}", re.I)),
    ("условие", re.compile(r"[^.\n]{0,80}(?:кроме|за исключением|если иное|при условии|не вправе|обязан)[^.\n]{0,80}", re.I)),
    ("решение", re.compile(r"[^.\n]{0,100}(?:решили|договорились|итог|вывод|принято решение|остановились на)[^.\n]{0,100}", re.I)),
    ("формула", re.compile(r"[^.\n]{0,40}=\s*[A-Za-zА-Яа-я0-9_()\[\]+\-*/., ]{6,}")),
]

# Значимые числа для сверки ответа с контекстом: длинные или с денежной меткой.
SIGNIFICANT_NUM_RE = re.compile(r"\b\d[\d\s]{3,}[\d]\b|\b\d+[.,]\d+\b|\b\d+\s*(?:руб|₽|\$|€|млн|млрд|тыс)\b", re.I)


def forces_full_context(question: str) -> bool:
    """Задача, где экономия запрещена независимо от режима."""
    return bool(FORCE_FULL_RE.search(question))


def extract_pins(text: str, source: str) -> list[tuple[str, str, str]]:
    """(вид, дословный фрагмент, источник) — то, что переживёт сжатие истории."""
    pins, seen = [], set()
    for kind, pattern in PIN_PATTERNS:
        for match in pattern.finditer(text):
            fragment = " ".join(match.group(0).split())
            if len(fragment) < 8 or fragment in seen:
                continue
            seen.add(fragment)
            pins.append((kind, fragment, source))
    return pins


def _normalize_numbers(text: str) -> set[str]:
    out = set()
    for match in SIGNIFICANT_NUM_RE.finditer(text):
        digits = re.sub(r"[^\d]", "", match.group(0))
        if len(digits) >= 3:
            out.add(digits)
    return out


def verify(answer: str, context: str, arithmetic_expected: bool) -> list[str]:
    """Числа в ответе, которых нет в поданном контексте.

    При расчётных задачах производные числа законны (сумма, разность), поэтому
    проверка там не применяется — иначе сплошные ложные срабатывания.
    """
    if arithmetic_expected:
        return []
    unknown = _normalize_numbers(answer) - _normalize_numbers(context)
    if not unknown:
        return []
    shown = ", ".join(sorted(unknown)[:5])
    return [f"в ответе есть числа, которых нет в поданном контексте: {shown}"]


SYSTEM_RULES = f"""Правила работы с контекстом:
- Если поданных данных недостаточно для точного ответа, начни ответ строкой
  {INSUFFICIENT} и одной фразой укажи, чего именно не хватает. Не догадывайся.
- Числа, даты, суммы и условия бери только из контекста, дословно. Не округляй
  и не пересказывай их своими словами.
- Если в контексте есть пометка о скрытых листах, сносках или сканах — учитывай её.
- Если видишь две редакции одного документа, не выбирай сам: скажи об этом явно."""
