def okrug_by_district(district: str | None) -> str | None:
    """Округ по названию района. Терпим к падежам и написанию через ё."""
    if not district:
        return None
    low = district.lower().replace("ё", "е").strip()

    # Голое «Москва» без района — не гадаем округ: иначе оно случайно
    # совпадёт по подстроке с «Москва-Сити» или «Новая Москва» и выдаст
    # ЦАО там, где на самом деле округ неизвестен.
    if low in ("москва", "г. москва", "г москва", "город москва"):
        return None

    for table in (DISTRICT_TO_OKRUG, LANDMARK_TO_OKRUG):
        for key, okrug in table.items():
            k = key.replace("ё", "е")
            # Проверка «low in k» только для достаточно длинных совпадений —
            # иначе короткое слово ложно матчится внутрь длинного ключа.
            if k in low or (len(low) >= 5 and low in k):
                return okrug
    return None


def okrug_from_text(text: str | None) -> str | None:
    """Округ прямо из текста: ищем и аббревиатуру, и название района."""
    if not text:
        return None
    upper = text.upper()
    for code in OKRUG_NAMES:
        if code.upper() in upper:
            return code
    return okrug_by_district(text)


