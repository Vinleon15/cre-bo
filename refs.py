def _norm(text: str | None) -> str:
    return (text or "").lower().replace("ё", "е")


def _district_variants(keys) -> list[str]:
    """Названия районов, плюс обратный порядок слов.

    В справочнике «северное чертаново», а в документах пишут «Чертаново
    Северное». Оба варианта — один и тот же район.
    """
    out = []
    for key in keys:
        k = key.replace("ё", "е")
        out.append(k)
        parts = k.split()
        if len(parts) == 2:
            out.append(f"{parts[1]} {parts[0]}")
    return out


def _bounded(words) -> str:
    return "|".join(r"\b" + re.escape(w) + r"\b" for w in words)


# Московская область проверяется раньше самого слова «Москва»: иначе
# «Московская область» посчиталась бы Москвой по корню «московск».
_MO_RE = re.compile(r"московск\w*\s+обл|моск\.?\s*обл|подмосков")
_MSK_RE = re.compile(r"москв|московск")
_OTHER_RE = re.compile("|".join(NON_MOSCOW_CITIES))
_REGION_RE = re.compile(r"\bобласт[ьи]\b|\bобл\.|\bкра[йея]\b|\bреспублик\w*")

_HIGHWAY_RE = r"\b(?:%s)\w*\s+(?:шоссе|ш\.)" % "|".join(MOSCOW_HIGHWAYS)
_PROSPECT_RE = r"\b(?:%s)\w*\s+(?:проспект\w*|просп\w*|пр-?кт\w*|пр-т)" % (
    "|".join(MOSCOW_PROSPECTS)
)
_MSK_ADDR_RE = re.compile("|".join([
    _HIGHWAY_RE,
    _PROSPECT_RE,
    _bounded(MOSCOW_LANDMARKS),
    _bounded(_district_variants(DISTRICT_TO_OKRUG)),
    _bounded(_district_variants(LANDMARK_TO_OKRUG)),
]))

# Округа как признак Москвы — все, кроме ЗАО: три эти буквы в новостях
# гораздо чаще означают закрытое акционерное общество, чем Западный
# округ. Западный округ и без того опознаётся по своим районам.
_OKRUG_CODES = tuple(c for c in OKRUG_NAMES if c != "ЗАО")


def city_verdict(text: str | None) -> str | None:
    """«moscow», «other» или None, если по этому куску текста не понять.

    Порядок проверок держится на том, что сильнее: область важнее корня
    «московск», прямое название города важнее названия улицы.
    """
    if not text:
        return None
    low = _norm(text)

    if _MO_RE.search(low):
        return "other"
    if _MSK_RE.search(low):
        return "moscow"
    if _OTHER_RE.search(low) or _REGION_RE.search(low):
        return "other"
    if any(code in text.upper() for code in _OKRUG_CODES):
        return "moscow"
    if _MSK_ADDR_RE.search(low):
        return "moscow"
    return None


